% run_abc_learned.m
% Fits the learning model parameters using Naive Posteriors as Priors.

clear

% load data
load('JulianMelissaData.mat') 
load('fractions.mat');

numDilutions = size(decisionsTotal,1);
numVoltages = size(decisionsTotal,2);

% extract decision counts in pre and post-learning epochs

e = [2 6]; % pre post
prePostDecsCounts = cell(numDilutions,numVoltages);
for d=1:numDilutions
    for v=1:numVoltages
        prePostDecsCounts{d,v} = decisionsTotal{d,v}(:,e);
    end
end

% Options for ABC-SMC
options = struct;
options.N = 2000;          % Number of particles
options.NT = options.N/2;         % Resampling threshold
options.alpha = 0.95;      % Tolerance decay
options.eps_target = 0.05; % Target epsilon (tune based on trial runs)
options.maxIter = 500;
options.M = 2;             % Simulation repeats per particle
options.verbose = true;
options.bisection_tol = 1e-3;
options.bisection_maxits = 40;
options.annotation = '';
options.min_stable_iters = 5;       
options.accept_rate_min = 0.001;    
options.resimulate_after_resampling = true;
options.min_stable_epsilon_iters = 10;
options.rel_eps_diff_tol = 1e-4;
options.increaseM = true;
options.printAlpha = true;

% Parameter setup
% Total params = 4 (naive) + 13 (learned) = 17
param_names = {'mu_ent','sig_ent','sl_mu_stay','sl_sig_stay', ... % 1-4
               'muS_15','muS_30','muS_60', ...                    % 5-7
               'off_0','off_15','off_30','off_60', ...            % 8-11
               'H','c','alpha','sigmaS_15','sigmaS_30','sigmaS_60', 'k'};  % 12-17

% prior limits on learned parameters
learned_lims = [
    -1 0;  % muS 15 
    -1.5   0;    % muS 30 
    -3 0; % muS 60 
    -0.3 0.3;   % offset 0
    -0.3 0.3;   % offset 15
    0 0.7;   % offset 30
    0 0.7;  % offset 60
    -30 -6;   % H
    0    0.2; %Ta 
    -0.5 0.5; %Tm
    0 1.5; % sigmaS 15 
    0 3; % sigmaS 30 
    0 3; % sigmaS 60 
    0 1; % k
];


% load naive posterior
S = load('naiveCombinedParams_theta_w_only.mat');
naive_particles = S.thetas_all_linear(:,1:4); %ignore the model dimension, we already selected only particles from the correct model
naive_weights = S.weights_all_linear;
% we already normalized the weights to sum to 1

% calculate the mean and weighted covariance of the naive particles
naive_mu = naive_weights' * naive_particles;
particles_centered = naive_particles - naive_mu;
naive_Sigma = particles_centered' * (particles_centered .* naive_weights);
naive_Sigma = naive_Sigma / (1 - sum(naive_weights.^2));

% Define Function Handles 

% Prior Sampler
% Draws naive params from bootstrap, learned params from uniform
priorSamplerFn = @(n) utils_learned.sample_hybrid_prior(n, naive_particles, naive_weights, learned_lims);

% Prior Log PDF
% Calculates density for learned params 
priorLogPdfFn = @(theta) utils_learned.log_prior_hybrid(theta, learned_lims, naive_mu, naive_Sigma);
%  Kernel Sampler 
kernelSamplerFn = @(theta_old, cholC) utils_learned.sample_block_kernel(theta_old, cholC);

% Set up ABC conditions
% The ABC run takes about 60-120 min on a 2021 MacBook Pro
% Given this length, it is convenient to run several iterations overnight
% but not convenient to run the entire analysis in one go, so in practice
% we comment in or comment out code to determine which type of analysis is
% used (synthetic negative control, positive control, real data,
% downsampled data etc)
% In this version, it is configured to run 10x repetitions on both
% synthetic neg ctrl data and real data
% Some commented-out code is left to illustrate how to run different
% conditions
 
% synthetic negative control data (Tm=0)
% learnedTmZero.mat was generated by using a version of this script to run ABC on 
% real data but inside the simulator function simFlyDecsLearnedTmK, set theta(14) = 0
S = load('learnedTmZero.mat'); 
negCtrl_thetas_all = [];
negCtrl_weights_all = [];
for i=1:length(S.results)
    negCtrl_thetas_all = [negCtrl_thetas_all; S.results(i).theta];
    negCtrl_weights_all = [negCtrl_weights_all; S.results(i).weights];
end
negCtrl_weights_all = negCtrl_weights_all/sum(negCtrl_weights_all);
negCtrl = negCtrl_weights_all' * negCtrl_thetas_all;
negCtrl(14) = 0;

% can also run a positive control e.g. by loading the mean posterior
% particle after running the full model on real data - the algorithm will
% recover the same particle with a spread from the stochasticity
ctrlParams = negCtrl; %[negCtrl; posCtrl]; 

numDataConds = 1; % could run with more conditions e.g. downsampling the data
numConds = size(ctrlParams,1) + numDataConds;
% conditions:
% 1. real data
% 2. neg ctrl

% just to quickly see an estimate
% in the paper we report the 95% HDI not the 95% CI
theta_weighted_95CI = zeros(size(ctrlParams,2),2,numConds);

numReps = 10; % how many times to repeat each condition

conditions = 1:numConds; 

for t=1:numReps
    for c= 1:numConds
        decsCounts = prePostDecsCounts;
        if c==2 
            % create separate negative control data set for each repetition
            obsData = simFlyDecsLearnedTmK(ctrlParams(1,:), decsCounts, fractions);
        else
            %
            obsData = cell(numDilutions, numVoltages);
            % % uncomment this code to downsample the data
            % downsampleFactor = 0.5;
            % e = [2 6];
            % for d = 1:numDilutions
            %     for v = 1:numVoltages
            %         numFlies = length(decisionsTotal{d,v});
            %         downsampledNum = floor(numFlies*downsampleFactor);
            %         downsampledIndices = randsample(numFlies,downsampledNum); % sample without replacement
            %         obsData{d,v} = zeros(downsampledNum,3,2);
            %         obsData{d,v}(:,1,:) = trainedOdorDecs{d,v}(downsampledIndices,e);
            %         obsData{d,v}(:,2,:) = decsTrainedOdorStay{d,v}(downsampledIndices,e);
            %         obsData{d,v}(:,3,:) = decsTrainedOdorEnter{d,v}(downsampledIndices,e);
            %         decsCounts{d,v} = decisionsTotal{d,v}(downsampledIndices,e);
            %     end
            % end
            % % %
            for d = 1:numDilutions
                for v = 1:numVoltages
                    numFlies = length(decisionsTotal{d,v});
                    obsData{d,v} = zeros(numFlies,3,2);
                    obsData{d,v}(:,1,:) = trainedOdorDecs{d,v}(:,e);
                    obsData{d,v}(:,2,:) = decsTrainedOdorStay{d,v}(:,e);
                    obsData{d,v}(:,3,:) = decsTrainedOdorEnter{d,v}(:,e);
                end
            end
        end

        % Simulator
        simulatorFn = @(theta) simFlyDecsLearnedTmK(theta, decsCounts, fractions);

        % Distance Function
        distanceFn = @(sim) utils_learned.CvMdivergenceLearned(sim, obsData);


        % --- 6. Run ABC ---
        disp('Starting ABC-SMC for Learned Behavior...');
        results(c,t) = abc_smc_adaptive_engine(simulatorFn, distanceFn, priorSamplerFn, ...
            priorLogPdfFn, kernelSamplerFn, options);

        % Save

        D = size(results(c,t).theta,2);
        for i=1:D
            theta_weighted_95CI(i,1,c,t) = wprctile(results(c,t).theta(:,i),2.5,results(c,t).weights);
            theta_weighted_95CI(i,2,c,t) = wprctile(results(c,t).theta(:,i),97.5,results(c,t).weights);
        end
        timestamp = datestr(now,'yymmddTHHMMSS');
        filename = ['learned_results_'  timestamp '.mat'];
        save(['/Users/aclin/Google Drive/Lab/Andrew_matlab/simulateMultiplex/abcoutput/' filename], ...
            'results', 'param_names', 'options', 'learned_lims', 'theta_weighted_95CI','ctrlParams','conditions','filename');
        writematrix(theta_weighted_95CI,['/Users/aclin/Google Drive/Lab/Andrew_matlab/simulateMultiplex/abcoutput/theta_weighted_95CI_' timestamp '.csv'])
    end
end

disp('Done.');

theta_weighted_95CI(14,:,:)


%% plot theta posteriors for just the first run


figure('Name',filename)
D = size(results(1).theta,2);
for d=1:D
    subplot(4,5,d)
    hold on
    [f,xi] = ksdensity(results(1).theta(:,d),'Weights', ...
        results(1).weights,'BoundaryCorrection','reflection');
    plot(xi,f)
    yl=ylim();
    if d>4
        line(learned_lims(d-4,1)*ones(1,2),yl,'Color','r')
        line(learned_lims(d-4,2)*ones(1,2),yl,'Color','r')
    else
        [f,xi] = ksdensity(naive_particles(:,d),'Weights', ...
            naive_weights,'BoundaryCorrection','reflection');
        plot(xi,f,'r')
    end
    
end

